"""``ce-lab market …`` -- anchors, priors, sales and room pressure.

Same rules as the rest of the CLI: validate inputs, exit non-zero on a usage
error, never show a traceback for something a user could reasonably get wrong,
and say plainly whether the inputs are fabricated or real.

No command may present a market price as our value or as a bid. What these print
is a **generic Sleeper anchor** and an **expected clearing price** under stated
scenarios; the championship-equity reservation range is a different quantity
computed elsewhere, and a tactical max bid is not built anywhere.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import List, Optional

from .anchors import AnchorError, load_sleeper_csv, match_anchors_to_contract
from .costbook import cost_book_from_market_state, cost_book_from_prior
from .demo import DEMO_SALES, build_demo_prior, demo_state
from .live import MarketState, SaleObservation, ShrinkageConfig
from .prior import MARKET_SCENARIOS, build_market_prior, format_prior_summary

__all__ = ["add_market_parser", "dispatch"]

_FABRICATED = (
    "INPUTS ARE FABRICATED. Anchors and prices are generated by a formula and\n"
    "describe no real player. Nothing below is a real market price.")

_REAL_BANNER = (
    "SOURCE: generic Sleeper 2026 '2qb' projected values. NOT this league's\n"
    "market, NOT championship-equity value, NOT a bid. Player-level output is\n"
    "written only to paths you name and must stay out of version control.")


class UsageError(Exception):
    """Something the caller can fix. Reported as a message, never a traceback."""


def _load_book(args):
    if not getattr(args, "csv", None):
        raise UsageError(
            "--csv is required for this command; there is no default path, "
            "because the anchor file lives outside version control")
    return load_sleeper_csv(args.csv, retrieved_at=getattr(args, "retrieved_at", None))


def _write_json(path: Optional[str], blob) -> None:
    if not path:
        return
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(blob, indent=2, default=str), encoding="utf-8")
    print(f"wrote {path}")


