"""``ce-lab auction …`` -- the auction layer's commands.

Kept out of ``cli.py`` because the auction layer is a package of its own and
its argument surface is large. Every command follows the same rules as the rest
of the CLI: validate inputs, exit non-zero on a usage error, never show a
traceback for something a user could reasonably get wrong, and say plainly
whether the inputs are fabricated and whether the answer is exact, heuristic or
unresolved.

No command may print an opening maximum, a recommended bid, or a predicted
clearing price. What they print is a CE reservation quantity under stated
assumptions.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from .completion import CompletionSettings, complete_roster, format_completion
from .costs import MissingCost
from .counterfactual import (PassDestination, compare_buy_vs_pass,
                             format_buy_pass)
from .demo import build_demo_auction
from .reservation import (ReservationCache, ScenarioSetup, estimate_runtime,
                          format_reservation, price_ladder, search_reservation)
from .state import AuctionError, AuctionRuleError, AuctionStateInvalid

__all__ = ["add_auction_parser", "dispatch"]

_FABRICATED_BANNER = (
    "INPUTS ARE FABRICATED. The player pool, the projections and the\n"
    "acquisition costs are all generated by a formula and describe no real\n"
    "player. Nothing printed below is a real value or a market price.")


def _settings(args) -> CompletionSettings:
    return CompletionSettings(
        beam_width=args.beam_width, candidate_pool=args.candidate_pool,
        finalists=args.finalists, ce_sims=args.sims, ce_seed=args.seed,
        proxy_seed=args.seed, max_runtime_s=args.max_seconds)


def _load(args):
    """Build the auction the command will run on.

    Only the fabricated demo exists as an input source today. A real auction
    state would arrive here as a file, and refusing clearly is better than
    inventing one: an auction state assembled from guesses would be a
    counterfactual pretending to be a room.
    """
    if getattr(args, "state", None):
        raise AuctionRuleError(
            "loading a real auction state from a file is not implemented; only "
            "--demo is available. Building one from guesses would be a "
            "counterfactual pretending to be a room.")
    demo = build_demo_auction()
    return demo


def _resolve_candidate(demo, args):
    if args.candidate is None:
        return demo.default_candidate().player_id
    if args.candidate not in demo.state.spec_by_id:
        raise AuctionRuleError(
            f"player {args.candidate} is not in this auction's pool")
    return args.candidate


def _pass_destination(args) -> PassDestination:
    if args.pass_to is None:
        return PassDestination.unavailable()
    if args.pass_price is None:
        raise AuctionRuleError(
            "--pass-to needs --pass-price: what the rival spends is money he no "
            "longer has, which is half of what the branch measures")
    return PassDestination.to_rival(args.pass_to, args.pass_price)


